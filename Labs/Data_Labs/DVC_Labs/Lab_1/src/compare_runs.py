"""Build reports/version_comparison.md from the JSON snapshots in reports/runs/.

Snapshot naming: <data_version>_<model>.json for scores and
<data_version>_data_report.json for the prepare-stage data report.
"""
import json
from pathlib import Path

RUNS = Path("reports/runs")
METRICS = ["accuracy", "precision", "recall", "f1", "roc_auc", "avg_precision"]

data_reports, scores = {}, []
for f in sorted(RUNS.glob("*.json")):
    version, rest = f.stem.split("_", 1)
    payload = json.loads(f.read_text())
    if rest == "data_report":
        data_reports[version] = payload
    else:
        scores.append((version, payload))

lines = ["# Dataset version & model comparison", "",
         "Generated by `python src/compare_runs.py` from `reports/runs/`.", "",
         "## Data versions (prepare stage)", "",
         "| version | raw rows | duplicates dropped | clean rows | positive rate | train / test |",
         "|---|---|---|---|---|---|"]
for v, r in sorted(data_reports.items()):
    lines.append(f"| {v} | {r['rows_raw']} | {r['rows_dropped_duplicates']} | "
                 f"{r['rows_clean']} | {r['positive_rate']:.2%} | "
                 f"{r['train_rows']} / {r['test_rows']} |")

lines += ["", "## Model scores (held-out test split)", "",
          "| data | model | " + " | ".join(METRICS) + " |",
          "|---|---|" + "---|" * len(METRICS)]
best = {m: max(s[m] for _, s in scores) for m in METRICS}
for v, s in scores:
    cells = [f"**{s[m]:.4f}**" if s[m] == best[m] else f"{s[m]:.4f}" for m in METRICS]
    lines.append(f"| {v} | {s['model']} | " + " | ".join(cells) + " |")

v2 = [s for v, s in scores if v == "v2"]
if v2:
    winner = max(v2, key=lambda s: s["f1"])
    lines += ["", f"**Selected model on v2 (by F1): `{winner['model']}`** "
              f"(F1 {winner['f1']:.4f}, ROC-AUC {winner['roc_auc']:.4f})."]

out = Path("reports/version_comparison.md")
out.write_text("\n".join(lines) + "\n")
print(out.read_text())
